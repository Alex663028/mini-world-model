def build():
    """组合生成对话语料。"""
    lines = []

    def add(q, a):
        lines.append(f"问：{q}\n答：{a}\n")

    # 身份自述：每个问法 × 每个答法（打散顺序，避免死板）
    for q in WHO_Q:
        for a in WHO:
            add(q, a)
    # 能力介绍
    for q in CAN_Q:
        for a in CAN:
            add(q, a)
    # 打招呼（问法与答法一一对应变体轮换）
    for i, q in enumerate(GREET_Q):
        add(q, GREET[i % len(GREET)])
        add(q, GREET[(i + 3) % len(GREET)])
    # 礼貌
    for q in THANKS_Q:
        for a in THANKS:
            add(q, a)
    for q in BYE_Q:
        for a in BYE:
            add(q, a)
    # 肯定否定
    for q in YES_Q:
        add(q, YES[len(lines) % len(YES)])
    for q in NO_Q:
        add(q, NO[len(lines) % len(NO)])
    # 场景问答
    for q, a in BOUND_Q + FAIL_Q:
        add(q, a)
        add(q.replace("？", ""), a)
    # 任务确认
    for q in TASK_Q:
        for a in TASK_READY:
            add(q, a)

    return "\n".join(lines)


