# 世界模型自述问答（这些答案来自项目自身的事实）
SELF_DIALOG = [
    ("世界模型是什么", "世界模型学习环境动态：给定观测和动作，预测下一刻的世界。"),
    ("世界模型有什么用", "它能在想象里试错和规划，不碰真实环境。"),
    ("你的世界模型长什么样", "编码器压图像，动力学预测潜状态，解码器画回来。"),
    ("你怕出错吗", "怕。想象越远误差越大，我的 MPC 只信十二步以内的梦。"),
    ("你会幻觉吗", "会。没学过的问法我会一本正经地编，这是语言模型的通病。"),
    ("你的梦想是什么", "把十二步想象延长到六十步，那时候 MPC 就不会迷路了。"),
]


def build_corpus():
    pairs = []

    # 1. 常识库扩充（每个 key 生成多种问法）
    for entry in ALL_KNOWLEDGE:
        for key in entry["keys"]:
            for tpl in TEMPLATES:
                q = tpl.format(key)
                if "？" in q or q.endswith("？"):
                    pairs.append((q, entry["answer"]))

    # 2. 通用对话
    pairs.extend(GENERAL_DIALOG)

    # 3. 世界模型自述
    pairs.extend(SELF_DIALOG)

    lines = []
    for q, a in pairs:
        lines.append(f"问：{q}\n答：{a}\n")
    return "\n".join(lines), pairs


if __name__ == "__main__":
    text, pairs = build_corpus()
    with open("corpus.txt", "w", encoding="utf-8") as f:
        f.write(text)
    chars = sorted(set(text))
    print(f"pairs: {len(pairs)}")
    print(f"chars: {len(chars)}")
    print(f"total chars: {len(text)}")
    print(f"vocab preview: {''.join(chars[:40])}...")
